import { readFile, writeFile } from 'node:fs/promises';
const config = JSON.parse(await readFile(new URL('../wrangler.jsonc', import.meta.url), 'utf8'));
const required = name => { const value = process.env[name]; if (!value) throw new Error(`Missing ${name}`); return value; };
const appId = required('PIPER_APP_ID');
if (!/^\d+$/.test(appId)) throw new Error('Numeric GitHub App ID required');
const bot = required('PIPER_BOT_LOGIN');
if (!/^[\w-]+\[bot\]$/.test(bot)) throw new Error('Expected GitHub App bot login');
const allowlist = required('PIPER_ALLOWLIST').split(',').map(x => x.trim());
if (allowlist.some(x => !/^[\w.-]+\/[\w.-]+$/.test(x))) throw new Error('Invalid repository allowlist');
const dryRun = process.env.PIPER_DRY_RUN || 'true';
if (!['true','false'].includes(dryRun)) throw new Error('PIPER_DRY_RUN must be true or false');
const defaults = process.env.PIPER_ORG_DEFAULTS || '{}'; JSON.parse(defaults);
const selected = config.env.production;
const emergencyStop = process.env.PIPER_EMERGENCY_STOP || 'false';
if (!['true','false'].includes(emergencyStop)) throw new Error('PIPER_EMERGENCY_STOP must be true or false');
const stopped = (process.env.PIPER_STOPPED_REPOSITORIES || '').split(',').map(x => x.trim()).filter(Boolean);
if (stopped.some(x => !/^[\w.-]+\/[\w.-]+$/.test(x))) throw new Error('Invalid stopped repositories');
const publicUrl = new URL(required('PIPER_WORKER_URL'));
if (publicUrl.protocol !== 'https:' || publicUrl.username || publicUrl.password || publicUrl.search || publicUrl.hash || publicUrl.pathname !== '/') throw new Error('PIPER_WORKER_URL must be an HTTPS origin');
Object.assign(selected.vars, { APP_ID: appId, BOT_LOGIN: bot, ALLOWED_REPOSITORIES: allowlist.join(','), DRY_RUN: dryRun, ORG_DEFAULTS: defaults, EMERGENCY_STOP: emergencyStop, STOPPED_REPOSITORIES: stopped.join(','), PUBLIC_URL: publicUrl.origin });
await writeFile('.piper.deploy.jsonc', JSON.stringify(config, null, 2) + '\n');
console.log(`Prepared production deployment configuration; dry-run=${dryRun}.`);
